import test from 'node:test';
import assert from 'node:assert/strict';
import { startRuntime } from './helpers.mjs';

// The real HTTP adapter, RPC binding and SQLite object jointly own these invariants.
test('core lifecycle, rejected writes, orchestration handoff and retained revisions', async t => {
  const runtime = await startRuntime();
  t.after(() => runtime.stop());
  const call = (name, args = {}) => runtime.call(name, args);
  const p = await call('create_project', { name: 'Household', actor: 'Eric' });
  const a = await call('create_lane', { project: p.id, name: 'Water', actor: 'one' });
  const b = await call('create_lane', { project: p.id, name: 'Power', actor: 'two' });
  const post = await call('post', { lane: a.id, actor: 'one', body: 'Evidence from fixture' });
  const cross = await call('post', { lane: b.id, actor: 'two', body: 'Other lane' });
  const work = await call('add_task', { lane: a.id, title: 'Inspect reserve', actor: 'one' });
  assert.equal(work.state, 'open');
  assert.equal(work.owner, null);
  const race = await Promise.allSettled(['one', 'two'].map(actor => call('claim_task', { task: work.id, actor })));
  assert.equal(race.filter(result => result.status === 'fulfilled').length, 1);
  const winner = race.find(result => result.status === 'fulfilled').value.owner;
  const loser = winner === 'one' ? 'two' : 'one';
  assert.match(String(race.find(result => result.status === 'rejected').reason), /owner=/);
  const before = await call('read_changes');
  await assert.rejects(call('post', { lane: a.id, actor: 'one', body: 'Bad reply', reply_to: cross.id }), /same lane/);
  await assert.rejects(call('submit_task', { task: work.id, actor: loser, post: post.id }), /owner/);
  await assert.rejects(call('submit_task', { task: work.id, actor: winner, post: cross.id }), /task lane/);
  assert.equal((await call('read_changes')).cursor, before.cursor);
  await call('submit_task', { task: work.id, actor: winner, post: post.id });
  const correction = await call('post', { lane: a.id, actor: loser, body: 'Please record the measured amount' });
  const revised = await call('review_task', { task: work.id, actor: loser, post: correction.id, action: 'revise' });
  assert.equal(revised.owner, winner);
  assert.equal(revised.state, 'working');
  const second = await call('post', { lane: a.id, actor: winner, body: 'Measured; evidence attached', reply_to: correction.id });
  await call('submit_task', { task: work.id, actor: winner, post: second.id });
  const accepted = await call('review_task', { task: work.id, actor: loser, post: correction.id, action: 'accept' });
  assert.equal(accepted.state, 'done');
  const events = (await call('read_changes')).events.filter(event => event.entity_id === work.id && event.kind === 'review_task');
  assert.equal(events.length, 2);
  const lane = await call('read_lane', { lane: a.id });
  assert.equal(lane.posts.find(row => row.id === post.id).body, 'Evidence from fixture');
  assert.equal(lane.posts.find(row => row.id === correction.id).body, 'Please record the measured amount');
  assert.equal(lane.tasks[0].result_post, second.id);
  assert.equal(lane.tasks[0].review_post, correction.id);
  const direct = await call('add_task', { lane: a.id, actor: 'researcher', title: 'Direct question' });
  await call('claim_task', { task: direct.id, actor: 'researcher' });
  await call('submit_task', { task: direct.id, actor: 'researcher', post: post.id });
  assert.equal((await call('review_task', { task: direct.id, actor: 'researcher', post: post.id, action: 'accept' })).state, 'done');

  await call('claim_orchestrator', { lane: a.id, actor: 'lead', runtime: 'codex', session: 'original' });
  await assert.rejects(call('claim_orchestrator', { lane: a.id, actor: 'lead', runtime: 'codex', session: 'fork' }), /owned by/);
  await call('claim_orchestrator', { lane: b.id, actor: 'peer', runtime: 'claude', session: 'other' });
  await call('claim_orchestrator', { lane: a.id, actor: 'lead', runtime: 'codex', session: 'original' });
  const handed = await call('handoff_orchestrator', { lane: a.id, actor: 'lead', session: 'original', new_actor: 'successor', new_runtime: 'claude', new_session: 'next', reason: 'Available peer' });
  assert.equal(handed.previous.session, 'original');
  assert.equal(handed.current.session, 'next');
  await assert.rejects(call('release_orchestrator', { lane: a.id, actor: 'lead', session: 'original' }), /owning/);
  await call('reassign_orchestrator', { lane: a.id, actor: 'Eric', new_actor: 'lead', new_runtime: 'codex', new_session: 'replacement', reason: 'Previous session ended' });
  assert.equal((await call('read_lane', { lane: a.id })).orchestration.session, 'replacement');
  await call('release_orchestrator', { lane: a.id, actor: 'lead', session: 'replacement' });
  assert.equal((await call('read_lane', { lane: a.id })).orchestration, null);
  assert.equal((await call('read_lane', { lane: b.id })).orchestration.actor, 'peer');
  await assert.rejects(call('read_changes', { after: 999999 }), /ahead of service/);
});
