import test from 'node:test';
import assert from 'node:assert/strict';
import { startRuntime } from './helpers.mjs';

test('followed work catches relevant updates and discovers sibling lanes without unchanged history', async t => {
  const runtime = await startRuntime();
  t.after(() => runtime.stop());
  const call = runtime.call.bind(runtime);
  const project = await call('create_project', { name: 'Home', actor: 'Eric' });
  const unrelated = await call('create_project', { name: 'Learning', actor: 'Eric' });
  const a = await call('create_lane', { project: project.id, name: 'Water', actor: 'one' });
  const b = await call('create_lane', { project: unrelated.id, name: 'Reading', actor: 'two' });
  const outcome = await call('add_task', { lane: a.id, actor: 'one', title: 'Prepare household' });
  const start = (await call('read_changes')).cursor;
  const sibling = await call('create_lane', { project: project.id, name: 'Power', actor: 'two', outcome_task: outcome.id });
  const hidden = await call('post', { lane: b.id, actor: 'two', body: 'Unrelated reading finding' });
  const siblingPost = await call('post', { lane: sibling.id, actor: 'two', body: 'Sibling finding' });
  const visible = await call('post', { lane: a.id, actor: 'one', body: 'Reserve measured' });
  const changes = await call('read_changes', { after: start, lanes: [a.id] });
  assert.ok(changes.events.some(event => event.kind === 'create_lane' && event.entity_id === sibling.id));
  assert.equal(changes.posts.find(post => post.id === visible.id).body, 'Reserve measured');
  assert.ok(!changes.posts.some(post => post.id === hidden.id));
  assert.ok(!changes.posts.some(post => post.id === siblingPost.id));
  assert.equal(changes.lanes.find(lane => lane.id === sibling.id).outcome_task, outcome.id);
  const projectChanges = await call('read_changes', { after: start, project: project.id });
  assert.ok(projectChanges.posts.some(post => post.id === siblingPost.id));
  assert.ok(!projectChanges.posts.some(post => post.id === hidden.id));
  const quiet = await call('read_changes', { after: changes.cursor, project: project.id });
  assert.deepEqual(quiet.events, []);
  assert.deepEqual(quiet.projects, []);
  assert.deepEqual(quiet.lanes, []);
  assert.deepEqual(quiet.posts, []);
  assert.deepEqual(quiet.tasks, []);
  await assert.rejects(call('read_changes', { project: unrelated.id, lanes: [a.id] }), /project/);
  await assert.rejects(call('create_lane', { project: unrelated.id, name: 'Missing outcome', actor: 'one', outcome_task: 999999 }), /task/);
  await assert.rejects(call('read_changes', { lanes: [999999] }), /lane/);

  let resolved = false;
  const waiting = call('wait_changes', { after: quiet.cursor, lanes: [a.id], timeout: 4 }).then(result => { resolved = true; return result; });
  await call('post', { lane: b.id, actor: 'two', body: 'No wake for other project' });
  await new Promise(resolve => setTimeout(resolve, 250));
  assert.equal(resolved, false);
  const answer = await call('post', { lane: a.id, actor: 'Eric', body: 'Use the basement shelf' });
  const resumed = await waiting;
  assert.equal(resumed.timed_out, false);
  assert.equal(resumed.posts.find(post => post.id === answer.id).body, 'Use the basement shelf');
  assert.ok(resumed.events.every(event => event.lane === a.id));
  await call('post', { lane: b.id, actor: 'two', body: 'Still unrelated' });
  const timedOut = await call('wait_changes', { after: resumed.cursor, lanes: [a.id], timeout: 0.2 });
  assert.equal(timedOut.timed_out, true);
  assert.deepEqual(timedOut.events, []);
  assert.ok(timedOut.cursor > resumed.cursor);

  await call('block_task', { task: outcome.id, actor: 'one', post: answer.id });
  const blockedElsewhere = await call('add_task', { lane: b.id, actor: 'two', title: 'Finish reading' });
  await call('block_task', { task: blockedElsewhere.id, actor: 'two', post: hidden.id });
  const afterBoth = (await call('read_changes')).cursor;
  const waitingSnapshot = await call('read_changes', { after: afterBoth, lanes: [a.id] });
  assert.deepEqual(waitingSnapshot.events, []);
  assert.deepEqual(waitingSnapshot.waiting.map(row => [row.id, row.waiting_post]), [[outcome.id, answer.id]]);
});
